# Every value in Python has a data type.
# type() tells us which data type a value has.

age = 27            # int   -> whole number
price = 99.99       # float -> decimal number
name = "Fazal"      # str   -> text
is_running = True   # bool  -> True or False

print(type(age))
print(type(price))
print(type(name))
print(type(is_running))

print(price)          # print the float value
print(is_running)     # print the bool value