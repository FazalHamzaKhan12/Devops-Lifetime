# Arithmetic operators perform mathematical calculations.

print(10 + 5)   # Addition          -> 15
print(10 - 5)   # Subtraction       -> 5
print(10 * 5)   # Multiplication    -> 50
print(10 / 5)   # Division          -> 2.0  (always returns a float)
print(10 // 5)  # Floor division    -> 2    (whole number division)
print(10 % 5)   # Modulus           -> 0    (the remainder of a division)
print(10 ** 2)  # Exponentiation    -> 100  (10 to the power of 2)

# These operators work with variables too.
x = 10
y = 4
print(x + y)   # 14
print(x % y)   # 2