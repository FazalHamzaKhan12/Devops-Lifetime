# Comparison operators compare two values and
# return a boolean result: True or False.

first = 5
second = 20

print(first == second)   # False, 5 is not equal to 20
print(first != second)   # True,  5 is not equal to 20

print(first < second)    # True,  5 is less than 20
print(first > second)    # False, 5 is not greater than 20

print(first <= second)   # True,  5 is less than or equal to 20
print(first >= second)   # False, 5 is not greater than or equal to 20